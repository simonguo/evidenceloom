export type I18nKey = keyof typeof dictionaries.zh;

export function createTranslator(language: SystemLanguage) {
  const dictionary = dictionaries[language] ?? dictionaries.zh;
  return (key: I18nKey, params?: Record<string, string | number>) => {
    const template = dictionary[key] ?? dictionaries.zh[key] ?? key;
    if (!params) return template;
    return Object.entries(params).reduce((value, [paramKey, paramValue]) => value.replaceAll(`{${paramKey}}`, String(paramValue)), template);
  };
}
